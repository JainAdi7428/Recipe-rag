"""Measure the web fallback on dishes this dataset does not have.

    python scripts/eval_web.py --limit 12          # a first batch
    python scripts/eval_web.py                     # the rest (resumes)
    python scripts/eval_web.py --report-only       # rebuild the report, no calls

Every dish goes through the whole pipeline with the web enabled, and each run is
appended to .artifacts/web_eval.json, so an interrupted run resumes rather than
re-spending Serper queries. The report is written to docs/web-evaluation.md.

Two populations, graded differently:

  real        dishes that exist in the world but not in this Epicurious corpus.
              The web should find them; reported as a success rate.
  fabricated  names invented for the test. The right outcome is the apology, and
              anything "found" is a fabricated source, listed for inspection.

The failure stage of every miss is recorded, because "nobody publishes this" and
"the publisher blocked us" call for completely different fixes.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

# Recipe titles arrive in any script: Korean, Japanese, accented French. The
# Windows console defaults to cp1252 and raises rather than printing them.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

sys.path.insert(0, str(Path(__file__).resolve().parent))

from recipe_rag import config
from recipe_rag.pipeline import (
    SOURCE_DATASET, SOURCE_NOT_FOUND, SOURCE_WEB, Pipeline,
)

from eval_gate import ABSENT_DISHES

RAW = config.ARTIFACT_DIR / "web_eval.json"
REPORT = Path(__file__).resolve().parent.parent / "docs" / "web-evaluation.md"

FABRICATED = {
    "Quantum Blockchain Smoothie", "Deep Fried Moon Rocks",
    "Unicorn Tears Consomme", "Gravitational Lasagna", "Photosynthesis Pie",
    "Recursive Onion Soup", "Tungsten Carbide Brownies",
}

STAGE_MEANING = {
    "no_results": "the search returned nothing usable",
    "fetch_failed": "every page blocked us or timed out",
    "no_markup": "pages carried no schema.org Recipe markup",
    "wrong_dish": "pages were a different dish, refused rather than answered",
    "diet_mismatch": "pages did not meet the stated diet",
    "search_failed": "Serper itself was unavailable",
    "timeout": "the whole web leg ran out of its time budget",
}


def load_rows() -> list[dict]:
    if not RAW.exists():
        return []
    return [
        json.loads(line)
        for line in RAW.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def run_dish(pipeline: Pipeline, dish: str) -> dict:
    answer = pipeline.answer(f"I need a recipe for {dish}", log=False)
    recipe = answer.recipe
    return {
        "dish": dish,
        "kind": "fabricated" if dish in FABRICATED else "real",
        "source": answer.source,
        "failure_stage": answer.failure_stage,
        "title": recipe.title if recipe else None,
        "domain": recipe.domain if recipe and recipe.url else None,
        "url": recipe.url if recipe else None,
        "pages_tried": len(answer.pages_tried),
        "coverage": answer.web_coverage,
        "seconds": round(answer.seconds, 1),
        "band": answer.band,
        "reasons": answer.reasons,
    }


def summarise(rows: list[dict]) -> dict:
    real = [r for r in rows if r["kind"] == "real"]
    fake = [r for r in rows if r["kind"] == "fabricated"]
    reached_web = [r for r in real if r["source"] != SOURCE_DATASET]
    answered = [r for r in reached_web if r["source"] == SOURCE_WEB]
    seconds = [r["seconds"] for r in rows] or [0.0]
    return {
        "rows": len(rows),
        "real": len(real),
        "from_dataset": len([r for r in real if r["source"] == SOURCE_DATASET]),
        "reached_web": len(reached_web),
        "answered": len(answered),
        "success": 100 * len(answered) / max(len(reached_web), 1),
        "stages": dict(Counter(r["failure_stage"] for r in reached_web if r["failure_stage"])),
        "domains": dict(Counter(r["domain"] for r in answered if r["domain"])),
        "fabricated": len(fake),
        "fabricated_answered": [r for r in fake if r["source"] != SOURCE_NOT_FOUND],
        "median_seconds": statistics.median(seconds),
        "max_seconds": max(seconds),
        "over_60s": len([s for s in seconds if s > 60]),
    }


def write_report(rows: list[dict], s: dict) -> None:
    out = [
        "# Web fallback - measured",
        "",
        f"Generated by `python scripts/eval_web.py` on {time.strftime('%Y-%m-%d')}. "
        f"Raw rows: `.artifacts/web_eval.json`.",
        "",
        "Every dish below goes through the whole pipeline with the web enabled. "
        "The dataset is Epicurious, so these dishes are mostly absent from it by design.",
        "",
        "## Summary",
        "",
        "| measure | value |",
        "|---|---|",
        f"| dishes tested | {s['rows']} ({s['real']} real, {s['fabricated']} fabricated) |",
        f"| real dishes answered from the dataset instead | {s['from_dataset']} |",
        f"| real dishes that reached the web | {s['reached_web']} |",
        f"| of those, answered from the web | {s['answered']} ({s['success']:.0f}%) |",
        f"| fabricated dishes wrongly answered | {len(s['fabricated_answered'])} (must be 0) |",
        f"| median response time | {s['median_seconds']:.1f}s |",
        f"| slowest response | {s['max_seconds']:.1f}s |",
        f"| responses over the 60s target | {s['over_60s']} |",
        "",
        "### Why the misses happened",
        "",
        "| stage | count | meaning |",
        "|---|---|---|",
    ]
    for stage, count in sorted(s["stages"].items(), key=lambda kv: -kv[1]):
        out.append(f"| `{stage}` | {count} | {STAGE_MEANING.get(stage, '')} |")
    if not s["stages"]:
        out.append("| - | 0 | every dish that reached the web was answered |")

    if s["domains"]:
        out += ["", "### Where the answers came from", "",
                "| site | recipes |", "|---|---|"]
        for domain, count in sorted(s["domains"].items(), key=lambda kv: -kv[1]):
            out.append(f"| {domain} | {count} |")

    if s["fabricated_answered"]:
        out += ["", "### Fabricated dishes that were answered - inspect these", ""]
        for row in s["fabricated_answered"]:
            out.append(f"- **{row['dish']}** -> {row['title']!r} ({row['domain']})")

    out += ["", "## Every dish", "",
            "| dish | outcome | recipe | site | stage | s |",
            "|---|---|---|---|---|---|"]
    labels = {SOURCE_WEB: "web", SOURCE_DATASET: "dataset", SOURCE_NOT_FOUND: "apology"}
    for row in sorted(rows, key=lambda r: (r["kind"], r["dish"])):
        out.append(
            f"| {row['dish']} | {labels[row['source']]} | {(row['title'] or '-')[:44]} | "
            f"{row['domain'] or '-'} | {row['failure_stage'] or '-'} | {row['seconds']:.0f} |"
        )
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(chr(10).join(out) + chr(10), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, help="run at most this many new dishes")
    parser.add_argument("--fresh", action="store_true", help="discard previous rows")
    parser.add_argument("--max-pages", type=int, default=4)
    parser.add_argument("--report-only", action="store_true",
                        help="rebuild the report from saved rows")
    args = parser.parse_args()

    if args.fresh and RAW.exists():
        RAW.unlink()
    rows = load_rows()

    if not args.report_only:
        done = {r["dish"] for r in rows}
        todo = [d for d in ABSENT_DISHES if d not in done]
        if args.limit:
            todo = todo[: args.limit]
        print(f"{len(done)} already measured, {len(todo)} to run")
        if todo:
            pipeline = Pipeline.load(use_judge=False, use_web=True, max_pages=args.max_pages)
            RAW.parent.mkdir(parents=True, exist_ok=True)
            with RAW.open("a", encoding="utf-8") as handle:
                for index, dish in enumerate(todo, 1):
                    row = run_dish(pipeline, dish)
                    handle.write(json.dumps(row, ensure_ascii=False) + chr(10))
                    handle.flush()
                    rows.append(row)
                    print(f"  {index:>2}/{len(todo)} {dish:<28} {row['source']:<10} "
                          f"{row['failure_stage'] or '-':<14} {row['seconds']:>5.1f}s  "
                          f"{(row['title'] or '')[:40]}")

    s = summarise(rows)
    write_report(rows, s)
    print(f"real dishes reaching the web: {s['reached_web']}, "
          f"answered {s['answered']} ({s['success']:.0f}%)")
    print(f"fabricated wrongly answered : {len(s['fabricated_answered'])} (must be 0)")
    print(f"median {s['median_seconds']:.1f}s, max {s['max_seconds']:.1f}s, "
          f"over 60s: {s['over_60s']}")
    print(f"stages: {s['stages']}")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
